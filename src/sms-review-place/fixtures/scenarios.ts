export function getScenarioById(id: string): SmsReviewScenario | undefined {
  return SCENARIOS.find((s) => s.id === id);
}

export function getEnabledScenarios(filter?: {
  scenarioId?: string;
  personaId?: string;
}): SmsReviewScenario[] {
  return SCENARIOS.filter((s) => {
    if (!s.enabled) return false;
    if (filter?.scenarioId && s.id !== filter.scenarioId) return false;
    if (filter?.personaId && s.personaId !== filter.personaId) return false;
    return true;
  });
}
